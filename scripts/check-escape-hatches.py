#!/usr/bin/env python3
"""Pin the unchecked construction paths (escape hatches) in the TCB crates.

A sealed or constrained type is only as strong as its unchecked exits: test
constructors, storage readback, trusted-caller constructors, raw exits and Kani
`assume_*` helpers. Each one is listed by path and function name in
`scripts/escape-hatch-inventory.json`, and any definition not in that list fails
the gate. An entry whose function no longer exists also fails, so the list stays
exact; `--ratchet` drops such entries and never adds one.

A function is an escape hatch when its name carries a `for_test` or `unchecked`
word, starts with `from_raw`, `from_stored`, `from_trusted`, `from_unchecked` or
`into_raw`, or starts with `assume_`. The definition counts whatever its `cfg`,
because a `#[cfg(test)]` constructor is still a reviewed way around the check.
`#[test]` functions and crate-level `tests`, `benches` and `examples` targets
are not counted: neither can construct a value for another caller.

The scan is lexical. Comments and literals are blanked first; a function
generated by a macro is not seen.
"""

import argparse
import importlib.util
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY = "scripts/escape-hatch-inventory.json"
SCHEMA = "chio.escape-hatch-inventory.v1"
DECLARED_ROOTS = ("crates/core/", "crates/security/", "crates/kernel/")
TARGET_DIRECTORIES = frozenset({"tests", "benches", "examples"})
HATCH_NAME = re.compile(
    r"^(?:\w+_)?(?:for_tests?|unchecked)(?:_\w+)?$|"
    r"^(?:from_(?:raw|stored|trusted|unchecked)|into_raw|assume)(?:_\w+)?$"
)
FN_ITEM = re.compile(r"\bfn\s+([A-Za-z_][A-Za-z0-9_]*)")
TEST_ATTRIBUTE = re.compile(
    r"#\[\s*(?:\w+\s*::\s*)*test\b[^\]]*\]\s*"
    r"(?:#\[[^\]]*\]\s*)*"
    r"(?:pub(?:\s*\([^)]*\))?\s+)?(?:(?:const|async|unsafe)\s+)*$"
)

spec = importlib.util.spec_from_file_location(
    "negative_assertions", ROOT / "scripts/check-negative-assertions.py"
)
lexer = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = lexer
spec.loader.exec_module(lexer)


def tcb_roots(root):
    """The declared roots plus every crate that holds a TCB library."""
    hardening = json.loads(
        (root / "docs/security/toolchain/rust-hardening.json").read_text()
    )
    crates = {
        "/".join(Path(path).parts[:3]) + "/"
        for path in hardening["tcb_libraries"].values()
    }
    return tuple(sorted(set(DECLARED_ROOTS) | crates))


def in_scope(path, roots):
    parts = path.split("/")
    return (
        path.startswith(roots)
        and len(parts) > 4
        and parts[3] not in TARGET_DIRECTORIES
    )


def hatches(path, source):
    scanned = lexer.blank_rust_noise(source)
    found = Counter()
    for match in FN_ITEM.finditer(scanned):
        name = match.group(1)
        if HATCH_NAME.match(name) and not TEST_ATTRIBUTE.search(
            scanned[max(0, match.start() - 400) : match.start()]
        ):
            found[f"{path}::{name}"] += 1
    return found


def inventory(root):
    paths = subprocess.check_output(
        [
            "git",
            "-C",
            str(root),
            "ls-files",
            "--cached",
            "--others",
            "--exclude-standard",
            "crates/*.rs",
            "crates/*.inc",
        ],
        text=True,
    )
    roots = tcb_roots(root)
    found = Counter()
    for path in sorted(set(paths.splitlines())):
        if in_scope(path, roots) and (root / path).is_file():
            found.update(hatches(path, (root / path).read_text()))
    return found


def load_allowed(root):
    document = json.loads((root / INVENTORY).read_text())
    if document.get("schema") != SCHEMA:
        raise ValueError(f"{INVENTORY}: schema is not {SCHEMA}")
    allowed = Counter(document["hatches"])
    for key, count in allowed.items():
        if type(count) is not int or count <= 0:
            raise ValueError(f"{INVENTORY}: {key}: count must be a positive integer")
        path, _, name = key.rpartition("::")
        if not path or not HATCH_NAME.match(name):
            raise ValueError(f"{INVENTORY}: {key}: not a path::escape-hatch key")
    return document, allowed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--ratchet", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        document, allowed = load_allowed(root)
        found = inventory(root)
    except (ValueError, KeyError, OSError, subprocess.CalledProcessError) as error:
        parser.error(str(error))
    added = found - allowed
    stale = allowed - found
    for key, count in sorted(added.items()):
        print(f"new escape hatch: {key} (+{count})", file=sys.stderr)
    if added:
        raise SystemExit(1)
    if stale and args.ratchet:
        document["hatches"] = dict(sorted((allowed & found).items()))
        (root / INVENTORY).write_text(json.dumps(document, indent=2) + "\n")
        for key in sorted(stale):
            print(f"dropped: {key}")
    elif stale:
        for key, count in sorted(stale.items()):
            print(
                f"removed escape hatch still listed: {key} (-{count}); run --ratchet",
                file=sys.stderr,
            )
        raise SystemExit(1)
    print(
        f"Escape hatches: {sum(found.values())} listed across "
        f"{len({key.rpartition('::')[0] for key in found})} files; no additions"
    )


if __name__ == "__main__":
    main()
