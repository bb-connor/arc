    def test_source_archive_is_read_to_its_end(self):
        alpha = ("p/a.c", b"/* Copyright 2001 Alpha */\n")
        beta = ("p/b.c", b"/* Copyright 2002 Beta */\n")
        whole = tar_archive([alpha], "raw")
        body = whole[: (len(tar_archive([alpha], "raw").rstrip(b"\0")) + 511) // 512 * 512]
        sparse = {"pax_headers": {"GNU.sparse.map": f"0,{len(beta[1])}", "GNU.sparse.size": str(len(beta[1]))}}
        for label, data, expected in (
            ("two gzip members", gzip.compress(body, mtime=0) + gzip.compress(tar_archive([beta], "raw"), mtime=0),
             b"line\t1\ts.tar.gz:p/b.c\t/* Copyright 2002 Beta */\n"),
            ("two xz streams", lzma.compress(body) + lzma.compress(tar_archive([beta], "raw")),
             b"line\t1\ts.tar.gz:p/b.c\t/* Copyright 2002 Beta */\n"),
            ("two bzip2 streams", bz2.compress(body) + bz2.compress(tar_archive([beta], "raw")),
             b"line\t1\ts.tar.gz:p/b.c\t/* Copyright 2002 Beta */\n"),
            ("contiguous member", gzip.compress(tar_archive([alpha, (*beta, {"type": tarfile.CONTTYPE})], "raw"),
                                                 mtime=0),
             b"line\t1\ts.tar.gz:p/b.c\t/* Copyright 2002 Beta */\n"),
            ("sparse member", gzip.compress(tar_archive([alpha, (*beta, sparse)], "raw"), mtime=0),
             b"unscanned-member\ts.tar.gz:p/b.c\n"),
            ("end-of-archive padding only", gzip.compress(whole + b"\0" * 10240, mtime=0),
             b"line\t1\ts.tar.gz:p/a.c\t/* Copyright 2001 Alpha */\n"),
            ("xz stream padding between streams", lzma.compress(body) + b"\0" * 4 + lzma.compress(tar_archive([beta], "raw")),
             b"line\t1\ts.tar.gz:p/b.c\t/* Copyright 2002 Beta */\n"),
            ("xz stream padding after the last stream", lzma.compress(whole) + b"\0" * 8,
             b"line\t1\ts.tar.gz:p/a.c\t/* Copyright 2001 Alpha */\n"),
        ):
            with self.subTest(label=label):
                self.assertIn(expected, self.scan_source(data))
        for label, data, fragment in (
            ("invalid header mid-archive", gzip.compress(body + b"\xff" * 512 + tar_archive([beta], "raw"), mtime=0),
             "s.tar.gz holds data after the end of its tar archive"),
            ("data after the end of the archive", gzip.compress(whole + b"Copyright 2002 Beta\n", mtime=0),
             "s.tar.gz holds data after the end of its tar archive"),
            ("garbage after the gzip member", gzip.compress(whole, mtime=0) + b"not gzip",
             "s.tar.gz is not a readable source archive"),
            ("truncated gzip member", gzip.compress(whole, mtime=0)[:-12], "s.tar.gz is not a readable source archive"),
            ("truncated xz stream", lzma.compress(whole)[:-20], "xz source ends inside a stream"),
            ("xz padding that is not a multiple of four", lzma.compress(whole) + b"\0" * 3,
             "xz stream padding is not a multiple of four bytes"),
            ("garbage after an xz stream", lzma.compress(whole) + b"not a stream",
             "xz source holds data after a stream that is not another stream"),
            ("garbage after a bzip2 stream", bz2.compress(whole) + b"not a stream",
             "bzip2 source holds data after a stream that is not another stream"),
            ("zero bytes between bzip2 streams", bz2.compress(body) + b"\0" * 4 + bz2.compress(tar_archive([beta], "raw")),
             "bzip2 source holds data after a stream that is not another stream"),
        ):
            with self.subTest(label=label):
                with self.assertRaises(CHECKER.SourcesError) as raised:
                    self.scan_source(data)
                self.assertEqual(str(raised.exception), fragment)

