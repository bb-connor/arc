    def test_long_line_listing_depends_on_content_only(self):
        class Pieces:
            def __init__(self, data: bytes, size: int):
                self.stream, self.size = io.BytesIO(data), size

            def read(self, size: int) -> bytes:
                return self.stream.read(min(size, self.size))

        content = (b"int a;\n" + b"u" * 300 + b"\n" + b"m" * 150 + b" Copy" + b"right 2015 " + b"m" * 150 + b"\n"
                   + b"/* Copyright (c) 2020 Short */\n" + b"n" * 200 + b"(c)  2019" + b"n" * 90)
        self.assertGreater(len(content), 16 * 8)
        limits = {"max_line_bytes": 64, "read_block_bytes": 16, "binary_probe_bytes": 1}
        with mock.patch.dict(CHECKER.ATTRIBUTION_METHOD, limits):
            renders = set()
            readers = [io.BytesIO(content)]
            readers += [CHECKER.Prefixed(content[:size], io.BytesIO(content[size:])) for size in (7, 33, 100, 171)]
            readers += [Pieces(content, size) for size in (1, 5, 17, 64, 1000)]
            for reader in readers:
                attribution = CHECKER.Attribution()
                attribution.scan("f", reader, len(content))
                renders.add(attribution.render("o"))
        self.assertEqual(len(renders), 1)
        render = renders.pop()
        self.assertIn(b"line\t1\tf\t/* Copyright (c) 2020 Short */\n", render)
        self.assertIn(b"long-lines\t2\tf\n", render)
        self.assertNotIn(b"mmmm", render)

