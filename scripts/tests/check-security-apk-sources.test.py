    def test_attribution_field_round_trips_exact_bytes(self):
        generator = random.Random(4)
        cases = [
            b"", b" ", b"\t", b"\\", b"\\x41", b"a\\x4", b"\r\n", b"\x00\x7f", b"caf\xc3\xa9", b"caf\xe9",
            b"\xc2\xa0\xe2\x80\xa8", b"\xed\xa0\x80", b"\xf4\x90\x80\x80", b"\t  // Copyright (c) 2022 \t \x0b  ",
        ]
        cases += [bytes(generator.randrange(256) for _ in range(generator.randrange(48))) for _ in range(3000)]
        cases += ["".join(chr(generator.choice((32, 92, 0x41, 0xa0, 0xe9, 0x2028, 0x1f600, 9)))
                          for _ in range(generator.randrange(24))).encode() for _ in range(1000)]
        for raw in cases:
            field = CHECKER.escape_field(raw)
            self.assertEqual(CHECKER.unescape_field(field), raw)
            self.assertEqual(CHECKER.escape_field(CHECKER.unescape_field(field)), field)
            self.assertFalse(any(char in field for char in "\t\r\n"), field)
            self.assertFalse(field.endswith((" ", "\t")), field)

