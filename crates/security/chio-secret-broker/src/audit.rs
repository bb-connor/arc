pub struct BrokerAuditExpectedContext<'a> {
    pub request: &'a BrokerExecuteRequest,
    pub audit_id: &'a str,
    pub reference_source: &'a str,
    pub reference_precommitment: &'a BrokerAuditReferencePrecommitment,
    pub revocation_authority_domain: &'a str,
    pub trust: BrokerAuditTrustConfiguration<'a>,
    pub not_before_unix_seconds: u64,
    pub expires_at_unix_seconds: u64,
}

/// Verify every public link in one audit comparison from independently trusted
/// typed evidence. No body digest is accepted as its own expected value.
pub fn verify_broker_audit_evidence(
    bundle: BrokerAuditEvidenceBundle<'_>,
    expected: BrokerAuditExpectedContext<'_>,
) -> Result<()> {
    expected.trust.validate()?;
    validate_identifier(expected.audit_id, "expected audit identifier", 512)?;
    validate_identifier(
        expected.reference_source,
        "expected audit reference source",
        512,
    )?;
    validate_digest(
        expected.reference_precommitment.commitment_sha256(),
        "expected audit reference commitment",
    )?;
    validate_identifier(
        expected.revocation_authority_domain,
        "expected audit revocation authority domain",
        512,
    )?;
    if expected.not_before_unix_seconds == 0
        || expected.expires_at_unix_seconds <= expected.not_before_unix_seconds
        || bundle.comparison.body.issued_at_unix_seconds < expected.not_before_unix_seconds
        || bundle.comparison.body.issued_at_unix_seconds >= expected.expires_at_unix_seconds
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit comparison is outside the expected evidence interval".to_string(),
        ));
    }
    verify_broker_audit_comparison(bundle.comparison, expected.trust.receipt_signer)?;
    crate::capability::verify_capability(
        &expected.request.capability,
        expected.trust.trusted_capability_issuer,
        expected.trust.broker_audience,
        bundle.comparison.body.issued_at_unix_seconds,
        true,
    )?;
    crate::proof::verify_request_proof(
        &expected.request.proof,
        &expected.request.capability,
        &expected.request.request,
        bundle.comparison.body.issued_at_unix_seconds,
        expected.trust.maximum_clock_skew_seconds,
    )?;
    if expected.request.capability.body.provider_adapter_id != expected.trust.provider_adapter_id
        || expected.request.capability.body.provider_adapter_version
            != expected.trust.provider_adapter_version
        || expected.request.request.destination != expected.request.capability.body.destination
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit request does not match the trusted provider configuration".to_string(),
        ));
    }

    let runner_body = &bundle.runner_authorization.body;
    bundle.runner_authorization.verify_signature()?;
    if &bundle.runner_authorization.signer != expected.trust.trusted_runner
        || runner_body.audit_id != expected.audit_id
        || runner_body.deployment_id != expected.trust.deployment_id
        || runner_body.broker_instance_id != expected.trust.broker_instance_id
        || runner_body.tenant_scope != expected.trust.tenant_scope
        || runner_body.runner_id != expected.trust.runner_id
        || runner_body.reference_source != expected.reference_source
        || runner_body.reference_commitment_sha256
            != expected.reference_precommitment.commitment_sha256()
        || runner_body.revocation_authority_domain != expected.revocation_authority_domain
        || runner_body.provider_adapter_id != expected.trust.provider_adapter_id
        || runner_body.provider_adapter_version != expected.trust.provider_adapter_version
        || runner_body.credential_provider != expected.request.capability.body.credential.provider
        || runner_body.capability_sha256 != capability_digest(&expected.request.capability)?
        || runner_body.proof_sha256 != proof_digest(&expected.request.proof)?
        || runner_body.canonical_request_sha256
            != broker_execute_request_registration_digest(expected.request)?
        || bundle.comparison.body.issued_at_unix_seconds < runner_body.issued_at_unix_seconds
        || bundle.comparison.body.issued_at_unix_seconds >= runner_body.expires_at_unix_seconds
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit runner evidence does not match the expected context".to_string(),
        ));
    }

    let runner_authorization_sha256 = runner_authorization_digest(bundle.runner_authorization)?;
    let governed_audit_intent_sha256 =
        broker_audit_governed_intent_digest(runner_body, &runner_authorization_sha256)?;
    let audit_authorization_sha256 = verify_governed_admin_authorization_evidence(
        bundle.admin_authorization,
        &governed_audit_intent_sha256,
        expected.trust.governed_admin_policy,
        bundle.comparison.body.issued_at_unix_seconds,
    )?;
    let authority_context_sha256 = broker_audit_authority_context_digest(
        expected.request,
        bundle.authority,
        expected.trust,
        expected.revocation_authority_domain,
        bundle.comparison.body.issued_at_unix_seconds,
    )?;

    if bundle.comparison.body.capability_sha256 != capability_digest(&expected.request.capability)?
        || bundle.comparison.body.proof_sha256 != proof_digest(&expected.request.proof)?
        || bundle.comparison.body.canonical_request_sha256
            != broker_execute_request_registration_digest(expected.request)?
        || bundle.comparison.body.authority_context_sha256 != authority_context_sha256
        || bundle.comparison.body.audit_id_sha256 != broker_audit_id_digest(expected.audit_id)?
        || bundle.comparison.body.governed_audit_intent_sha256 != governed_audit_intent_sha256
        || bundle.comparison.body.audit_authorization_sha256 != audit_authorization_sha256
        || bundle.comparison.body.runner_authorization_sha256 != runner_authorization_sha256
        || bundle.comparison.body.reference_source_sha256
            != broker_audit_reference_source_digest(expected.reference_source)?
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit comparison does not bind the independently verified evidence".to_string(),
        ));
    }
    Ok(())
}

pub(crate) struct BrokerAuditWireComparison {
    pub(crate) broker_projection_commitment_sha256: String,
    pub(crate) reference_projection_commitment_sha256: String,
    pub(crate) projections_equal: bool,
}

pub(crate) struct BrokerAuditComparisonSalt(Zeroizing<[u8; 32]>);

impl BrokerAuditComparisonSalt {
    pub(crate) fn generate() -> Result<Self> {
        let mut salt = Zeroizing::new([0_u8; 32]);
        OsRng.try_fill_bytes(&mut salt[..]).map_err(|_| {
            BrokerError::AuthorityUnavailable(
                "broker audit comparison randomness is unavailable".to_string(),
            )
        })?;
        if salt.iter().all(|byte| *byte == 0) {
            return Err(BrokerError::AuthorityUnavailable(
                "broker audit comparison randomness is invalid".to_string(),
            ));
        }
        Ok(Self(salt))
    }

    fn as_bytes(&self) -> &[u8] {
        &self.0[..]
    }
}

pub(crate) fn compare_audit_wire_requests(
    comparison_salt: &BrokerAuditComparisonSalt,
    broker_request_head: &[u8],
    broker_request_body: &[u8],
    reference: BrokerAuditReferenceRequest,
) -> Result<BrokerAuditWireComparison> {
    reference.validate()?;
    if broker_request_head.is_empty()
        || broker_request_head.len() > MAX_WIRE_BYTES
        || !broker_request_head.ends_with(b"\r\n\r\n")
        || broker_request_body.len() > MAX_BODY_BYTES
    {
        return Err(BrokerError::Invariant(
            "prepared broker audit request is malformed or oversized".to_string(),
        ));
    }
    let broker_tag = audit_projection_commitment(
        comparison_salt.as_bytes(),
        broker_request_head,
        broker_request_body,
    )?;
    let reference_tag = audit_projection_commitment(
        comparison_salt.as_bytes(),
        &reference.request_head,
        &reference.request_body,
    )?;
    let projections_equal = bool::from(
        broker_request_head.ct_eq(reference.request_head.as_slice())
            & broker_request_body.ct_eq(reference.request_body.as_slice()),
    );
    Ok(BrokerAuditWireComparison {
        broker_projection_commitment_sha256: hex::encode(broker_tag),
        reference_projection_commitment_sha256: hex::encode(reference_tag),
        projections_equal,
    })
}

pub fn broker_audit_authority_context_digest(
    request: &BrokerExecuteRequest,
    authority: BrokerAuditAuthorityEvidence<'_>,
    trust: BrokerAuditTrustConfiguration<'_>,
    revocation_authority_domain: &str,
    validated_at_unix_seconds: u64,
) -> Result<String> {
    request.validate_bounds()?;
    trust.validate()?;
    validate_identifier(
        revocation_authority_domain,
        "audit revocation authority domain",
        512,
    )?;
    if validated_at_unix_seconds == 0 {
        return Err(BrokerError::InvalidRequest(
            "audit authority validation time is invalid".to_string(),
        ));
    }

    for exchange in [authority.liveness, authority.revocation] {
        if exchange.trusted_authority() != trust.trusted_authority {
            return Err(BrokerError::AuthorizationDenied(
                "broker audit authority evidence uses an unexpected trust root".to_string(),
            ));
        }
        crate::authority_ipc::verify_authority_exchange(
            exchange.request().clone(),
            exchange.response().clone(),
            trust.trusted_authority,
            validated_at_unix_seconds,
            trust.maximum_clock_skew_seconds,
        )?;
    }

    let liveness_request = CapabilityLivenessRequest {
        parent_capability_id: request.capability.body.parent_capability_id.clone(),
        expected_subject: request.capability.body.subject.clone(),
        expected_audience: trust.parent_audience.to_string(),
        now_unix_seconds: validated_at_unix_seconds,
    };
    if authority.liveness.request().body.operation
        != AuthorityOperation::VerifyLiveParent(liveness_request.clone())
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit liveness evidence is bound to another request".to_string(),
        ));
    }
    let AuthorityResult::LiveParent(live_parent) = &authority.liveness.response().body.result
    else {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit liveness evidence has the wrong result".to_string(),
        ));
    };
    validate_parent_liveness(
        &liveness_request,
        live_parent,
        trust.maximum_liveness_snapshot_age_seconds,
    )?;

    let revocation_request = BrokerRevocationRequest {
        broker_capability_id: request.capability.body.capability_id.clone(),
        revocation_id: request.capability.body.revocation_id.clone(),
        now_unix_seconds: validated_at_unix_seconds,
    };
    if authority.revocation.request().body.operation
        != AuthorityOperation::CheckBrokerRevocation(revocation_request.clone())
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit revocation evidence is bound to another request".to_string(),
        ));
    }
    let AuthorityResult::Revocation(revocation_snapshot) =
        &authority.revocation.response().body.result
    else {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit revocation evidence has the wrong result".to_string(),
        ));
    };
    validate_revocation_snapshot(
        revocation_snapshot,
        validated_at_unix_seconds,
        trust.maximum_revocation_snapshot_age_seconds,
        revocation_authority_domain,
    )?;
    let revocation_set = CanonicalBrokerRevocationSet::new(
        &request.capability.body.parent_capability_id,
        &live_parent.delegation_ancestor_ids,
        &request.capability.body.capability_id,
        &request.capability.body.revocation_id,
    )?;
    let trusted_configuration_sha256 = trust.digest()?;
    let liveness_authority_request_sha256 = authority.liveness.request_sha256()?;
    let liveness_authority_response_sha256 = authority.liveness.response_sha256()?;
    let revocation_authority_request_sha256 = authority.revocation.request_sha256()?;
    let revocation_authority_response_sha256 = authority.revocation.response_sha256()?;

    #[derive(Serialize)]
    #[serde(rename_all = "camelCase", deny_unknown_fields)]
    struct AuthorityContext<'a> {
        domain: &'static str,
        revocation_authority_domain: &'a str,
        revocation_set_sha256: &'a str,
        live_parent: &'a crate::revocation::LiveParentCapability,
        revocation_snapshot: &'a crate::revocation::BrokerRevocationSnapshot,
        trusted_authority: &'a PublicKey,
        liveness_authority_request_sha256: &'a str,
        liveness_authority_response_sha256: &'a str,
        revocation_authority_request_sha256: &'a str,
        revocation_authority_response_sha256: &'a str,
        trusted_configuration_sha256: &'a str,
        validated_at_unix_seconds: u64,
    }
    let canonical = canonical_json_bytes(&AuthorityContext {
        domain: BROKER_AUDIT_AUTHORITY_CONTEXT_DOMAIN,
        revocation_authority_domain,
        revocation_set_sha256: revocation_set.digest(),
        live_parent,
        revocation_snapshot,
        trusted_authority: trust.trusted_authority,
        liveness_authority_request_sha256: &liveness_authority_request_sha256,
        liveness_authority_response_sha256: &liveness_authority_response_sha256,
        revocation_authority_request_sha256: &revocation_authority_request_sha256,
        revocation_authority_response_sha256: &revocation_authority_response_sha256,
        trusted_configuration_sha256: &trusted_configuration_sha256,
        validated_at_unix_seconds,
    })
    .map_err(|error| {
        BrokerError::Invariant(format!(
            "broker audit authority context encoding failed: {error}"
        ))
    })?;
    Ok(hex::encode(Sha256::digest(canonical)))
}

fn audit_projection_commitment(
    salt: &[u8],
    request_head: &[u8],
    request_body: &[u8],
) -> Result<[u8; 32]> {
    let request_head_len = u64::try_from(request_head.len()).map_err(|_| {
        BrokerError::InvalidRequest("broker audit request head length overflow".to_string())
    })?;
    let request_body_len = u64::try_from(request_body.len()).map_err(|_| {
        BrokerError::InvalidRequest("broker audit request body length overflow".to_string())
    })?;
    if salt.len() != 32 || salt.iter().all(|byte| *byte == 0) {
        return Err(BrokerError::Invariant(
            "broker audit comparison salt is invalid".to_string(),
        ));
    }
    let mut hasher = Sha256::new();
    hasher.update(BROKER_AUDIT_PROJECTION_DOMAIN);
    hasher.update(request_head_len.to_be_bytes());
    hasher.update(request_head);
    hasher.update(request_body_len.to_be_bytes());
    hasher.update(request_body);
    hasher.update(salt);
    hasher.update([0_u8; 64]);
    Ok(hasher.finalize().into())
}

