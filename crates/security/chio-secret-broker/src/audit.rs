/// Runner-owned commitment retained before any privileged broker connection.
///
/// The salt is generated by the audit runner and the commitment is derived
/// from the runner's original reference bytes. Private fields prevent a caller
/// from manufacturing this typed expectation by copying a digest out of a
/// broker-signed response.
pub struct BrokerAuditReferencePrecommitment {
    commitment_salt: Zeroizing<String>,
    commitment_sha256: String,
}

impl BrokerAuditReferencePrecommitment {
    pub fn generate(request_head: &[u8], request_body: &[u8]) -> Result<Self> {
        validate_reference_request_parts(request_head, request_body)?;
        let mut salt = Zeroizing::new([0_u8; BROKER_AUDIT_REFERENCE_COMMITMENT_SALT_BYTES]);
        OsRng.try_fill_bytes(&mut salt[..]).map_err(|_| {
            BrokerError::AuthorityUnavailable(
                "broker audit runner precommitment randomness is unavailable".to_string(),
            )
        })?;
        if salt.iter().all(|byte| *byte == 0) {
            return Err(BrokerError::AuthorityUnavailable(
                "broker audit runner precommitment randomness is invalid".to_string(),
            ));
        }
        let commitment_salt = Zeroizing::new(hex::encode(salt.as_slice()));
        let commitment_sha256 = broker_audit_reference_commitment_sha256(
            commitment_salt.as_str(),
            request_head,
            request_body,
        )?;
        Ok(Self {
            commitment_salt,
            commitment_sha256,
        })
    }

    #[must_use]
    pub fn commitment_salt(&self) -> &str {
        self.commitment_salt.as_str()
    }

    #[must_use]
    pub fn commitment_sha256(&self) -> &str {
        &self.commitment_sha256
    }
}

impl fmt::Debug for BrokerAuditReferencePrecommitment {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("BrokerAuditReferencePrecommitment")
            .field("commitment_salt", &"<redacted>")
            .field("commitment_sha256", &self.commitment_sha256)
            .finish()
    }
}

/// Exact legacy outbound bytes admitted only into the privileged in-process
/// migration audit path. The buffers are zeroized on every return path and
/// cannot be cloned, serialized, or inspected through `Debug`.
pub struct BrokerAuditReferenceRequest {
    commitment_salt: Zeroizing<String>,
    request_head: Zeroizing<Vec<u8>>,
    request_body: Zeroizing<Vec<u8>>,
}

impl BrokerAuditReferenceRequest {
    pub fn new_with_precommitment(
        request_head: Vec<u8>,
        request_body: Vec<u8>,
    ) -> Result<(Self, BrokerAuditReferencePrecommitment)> {
        let precommitment =
            BrokerAuditReferencePrecommitment::generate(&request_head, &request_body)?;
        let reference = Self::from_precommitment(
            request_head,
            request_body,
            precommitment.commitment_salt().to_string(),
            precommitment.commitment_sha256(),
        )?;
        Ok((reference, precommitment))
    }

    pub(crate) fn from_precommitment(
        request_head: Vec<u8>,
        request_body: Vec<u8>,
        commitment_salt: String,
        expected_commitment_sha256: &str,
    ) -> Result<Self> {
        let observed_commitment_sha256 = broker_audit_reference_commitment_sha256(
            &commitment_salt,
            &request_head,
            &request_body,
        )?;
        if observed_commitment_sha256 != expected_commitment_sha256 {
            return Err(BrokerError::AuthorizationDenied(
                "broker audit reference does not match the runner precommitment".to_string(),
            ));
        }
        let reference = Self {
            commitment_salt: Zeroizing::new(commitment_salt),
            request_head: Zeroizing::new(request_head),
            request_body: Zeroizing::new(request_body),
        };
        reference.validate()?;
        Ok(reference)
    }

    pub(crate) fn validate(&self) -> Result<()> {
        validate_reference_request_parts(
            self.request_head.as_slice(),
            self.request_body.as_slice(),
        )?;
        validate_reference_commitment_salt(self.commitment_salt.as_str())
    }
}

impl fmt::Debug for BrokerAuditReferenceRequest {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("BrokerAuditReferenceRequest")
            .field("commitment_salt", &"<redacted>")
            .field("request_head", &"<redacted>")
            .field("request_body", &"<redacted>")
            .finish()
    }
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct BrokerAuditRunnerAuthorizationBody {
    pub schema: String,
    pub audit_id: String,
    pub deployment_id: String,
    pub broker_instance_id: String,
    pub tenant_scope: String,
    pub runner_id: String,
    pub reference_source: String,
    pub reference_commitment_sha256: String,
    pub capability_sha256: String,
    pub proof_sha256: String,
    pub canonical_request_sha256: String,
    pub provider_adapter_id: String,
    pub provider_adapter_version: u32,
    pub credential_provider: String,
    pub revocation_authority_domain: String,
    pub issued_at_unix_seconds: u64,
    pub expires_at_unix_seconds: u64,
}

impl BrokerAuditRunnerAuthorizationBody {
    pub fn for_request(
        request: &BrokerExecuteRequest,
        reference: &BrokerAuditReferenceRequest,
        scope: BrokerAuditRunnerScope<'_>,
        issued_at_unix_seconds: u64,
        expires_at_unix_seconds: u64,
    ) -> Result<Self> {
        reference.validate()?;
        request.validate_bounds()?;
        let body = Self {
            schema: BROKER_AUDIT_RUNNER_AUTHORIZATION_SCHEMA.to_string(),
            audit_id: scope.audit_id.to_string(),
            deployment_id: scope.deployment_id.to_string(),
            broker_instance_id: scope.broker_instance_id.to_string(),
            tenant_scope: scope.tenant_scope.to_string(),
            runner_id: scope.runner_id.to_string(),
            reference_source: scope.reference_source.to_string(),
            reference_commitment_sha256: reference_request_digest(reference)?,
            capability_sha256: capability_digest(&request.capability)?,
            proof_sha256: proof_digest(&request.proof)?,
            canonical_request_sha256: broker_execute_request_registration_digest(request)?,
            provider_adapter_id: request.capability.body.provider_adapter_id.clone(),
            provider_adapter_version: request.capability.body.provider_adapter_version,
            credential_provider: request.capability.body.credential.provider.clone(),
            revocation_authority_domain: scope.revocation_authority_domain.to_string(),
            issued_at_unix_seconds,
            expires_at_unix_seconds,
        };
        body.validate()?;
        Ok(body)
    }

    pub fn validate(&self) -> Result<()> {
        if self.schema != BROKER_AUDIT_RUNNER_AUTHORIZATION_SCHEMA
            || self.issued_at_unix_seconds == 0
            || self.expires_at_unix_seconds <= self.issued_at_unix_seconds
            || self
                .expires_at_unix_seconds
                .saturating_sub(self.issued_at_unix_seconds)
                > MAX_AUDIT_RUNNER_AUTHORIZATION_LIFETIME_SECONDS
            || self.provider_adapter_version == 0
        {
            return Err(BrokerError::InvalidRequest(
                "broker audit runner authorization schema, time, or version is invalid".to_string(),
            ));
        }
        for (value, label) in [
            (&self.audit_id, "broker audit identifier"),
            (&self.deployment_id, "broker audit deployment identifier"),
            (&self.broker_instance_id, "broker audit instance identifier"),
            (&self.tenant_scope, "broker audit tenant scope"),
            (&self.runner_id, "broker audit runner identifier"),
            (&self.reference_source, "broker audit reference source"),
            (&self.provider_adapter_id, "broker audit provider adapter"),
            (
                &self.credential_provider,
                "broker audit credential provider",
            ),
            (
                &self.revocation_authority_domain,
                "broker audit revocation authority domain",
            ),
        ] {
            validate_identifier(value, label, 512)?;
        }
        for (digest, label) in [
            (
                &self.reference_commitment_sha256,
                "broker audit reference commitment",
            ),
            (&self.capability_sha256, "broker audit capability digest"),
            (&self.proof_sha256, "broker audit proof digest"),
            (
                &self.canonical_request_sha256,
                "broker audit canonical request digest",
            ),
        ] {
            validate_digest(digest, label)?;
        }
        Ok(())
    }
}

#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SignedBrokerAuditRunnerAuthorization {
    pub body: BrokerAuditRunnerAuthorizationBody,
    pub signer: PublicKey,
    pub algorithm: SigningAlgorithm,
    pub signature: Signature,
}

impl SignedBrokerAuditRunnerAuthorization {
    pub fn sign(
        body: BrokerAuditRunnerAuthorizationBody,
        signer: &dyn SigningBackend,
    ) -> Result<Self> {
        body.validate()?;
        let canonical = runner_authorization_signing_bytes(&body)?;
        let outcome = signer
            .sign_bytes_with_identity(&canonical)
            .map_err(|error| {
                BrokerError::AuthorityUnavailable(format!(
                    "broker audit runner authorization signing failed: {error}"
                ))
            })?;
        if outcome.public_key.algorithm() != outcome.algorithm
            || outcome.signature.algorithm() != outcome.algorithm
            || !outcome.public_key.verify(&canonical, &outcome.signature)
        {
            return Err(BrokerError::Invariant(
                "broker audit runner signer returned invalid identity metadata".to_string(),
            ));
        }
        Ok(Self {
            body,
            signer: outcome.public_key,
            algorithm: outcome.algorithm,
            signature: outcome.signature,
        })
    }

    pub fn canonical_bytes(&self) -> Result<Vec<u8>> {
        self.verify_signature()?;
        canonical_json_bytes(self).map_err(|error| {
            BrokerError::Invariant(format!(
                "broker audit runner authorization encoding failed: {error}"
            ))
        })
    }

    pub fn from_canonical_bytes(bytes: &[u8]) -> Result<Self> {
        if bytes.is_empty() || bytes.len() > MAX_WIRE_BYTES {
            return Err(BrokerError::InvalidRequest(
                "broker audit runner authorization is empty or oversized".to_string(),
            ));
        }
        let authorization: Self = serde_json::from_slice(bytes).map_err(|error| {
            BrokerError::InvalidRequest(format!(
                "broker audit runner authorization decoding failed: {error}"
            ))
        })?;
        authorization.verify_signature()?;
        if canonical_json_bytes(&authorization).map_err(|error| {
            BrokerError::InvalidRequest(format!(
                "broker audit runner authorization encoding failed: {error}"
            ))
        })? != bytes
        {
            return Err(BrokerError::InvalidRequest(
                "broker audit runner authorization is not canonical JSON".to_string(),
            ));
        }
        Ok(authorization)
    }

    fn verify_signature(&self) -> Result<()> {
        self.body.validate()?;
        if self.signer.algorithm() != self.algorithm
            || self.signature.algorithm() != self.algorithm
            || !self.signer.verify(
                &runner_authorization_signing_bytes(&self.body)?,
                &self.signature,
            )
        {
            return Err(BrokerError::AuthorizationDenied(
                "broker audit runner authorization signature is invalid".to_string(),
            ));
        }
        Ok(())
    }
}

