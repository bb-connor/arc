pub fn verify_broker_audit_runner_authorization(
    authorization: &SignedBrokerAuditRunnerAuthorization,
    request: &BrokerExecuteRequest,
    reference: &BrokerAuditReferenceRequest,
    trust: BrokerAuditRunnerTrust<'_>,
    now_unix_seconds: u64,
) -> Result<VerifiedBrokerAuditRunnerAuthorization> {
    authorization.verify_signature()?;
    reference.validate()?;
    for (value, label) in [
        (trust.deployment_id, "trusted audit deployment identifier"),
        (trust.broker_instance_id, "trusted audit broker instance"),
        (trust.tenant_scope, "trusted audit tenant scope"),
        (trust.runner_id, "trusted audit runner identifier"),
    ] {
        validate_identifier(value, label, 512)?;
    }
    let body = &authorization.body;
    if &authorization.signer != trust.trusted_runner
        || now_unix_seconds < body.issued_at_unix_seconds
        || now_unix_seconds >= body.expires_at_unix_seconds
        || body.deployment_id != trust.deployment_id
        || body.broker_instance_id != trust.broker_instance_id
        || body.tenant_scope != trust.tenant_scope
        || body.runner_id != trust.runner_id
        || body.reference_commitment_sha256 != reference_request_digest(reference)?
        || body.capability_sha256 != capability_digest(&request.capability)?
        || body.proof_sha256 != proof_digest(&request.proof)?
        || body.canonical_request_sha256 != broker_execute_request_registration_digest(request)?
        || body.provider_adapter_id != request.capability.body.provider_adapter_id
        || body.provider_adapter_version != request.capability.body.provider_adapter_version
        || body.credential_provider != request.capability.body.credential.provider
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit runner authorization is stale, untrusted, or rebound".to_string(),
        ));
    }
    let runner_authorization_sha256 = runner_authorization_digest(authorization)?;
    let governed_intent_sha256 =
        broker_audit_governed_intent_digest(body, &runner_authorization_sha256)?;
    Ok(VerifiedBrokerAuditRunnerAuthorization {
        governed_intent_sha256,
        runner_authorization_sha256,
        audit_id_sha256: broker_audit_id_digest(&body.audit_id)?,
        reference_source_sha256: broker_audit_reference_source_digest(&body.reference_source)?,
        revocation_authority_domain: body.revocation_authority_domain.clone(),
        deployment_id: body.deployment_id.clone(),
        broker_instance_id: body.broker_instance_id.clone(),
        tenant_scope: body.tenant_scope.clone(),
        runner_id: body.runner_id.clone(),
        trusted_runner: trust.trusted_runner.clone(),
    })
}

