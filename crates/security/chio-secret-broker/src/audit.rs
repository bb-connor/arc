impl BrokerAuditComparisonBody {
    pub fn validate(&self) -> Result<()> {
        if self.schema != BROKER_AUDIT_COMPARISON_SCHEMA || self.issued_at_unix_seconds == 0 {
            return Err(BrokerError::InvalidRequest(
                "broker audit comparison schema or issue time is invalid".to_string(),
            ));
        }
        for (digest, label) in [
            (&self.capability_sha256, "audit capability digest"),
            (&self.proof_sha256, "audit proof digest"),
            (
                &self.canonical_request_sha256,
                "audit canonical request digest",
            ),
            (
                &self.authority_context_sha256,
                "audit authority context digest",
            ),
            (&self.audit_id_sha256, "audit identifier digest"),
            (
                &self.governed_audit_intent_sha256,
                "governed audit intent digest",
            ),
            (
                &self.audit_authorization_sha256,
                "audit authorization digest",
            ),
            (
                &self.runner_authorization_sha256,
                "audit runner authorization digest",
            ),
            (
                &self.reference_source_sha256,
                "audit reference source digest",
            ),
            (
                &self.broker_outbound_projection_commitment_sha256,
                "audit broker projection digest",
            ),
            (
                &self.reference_outbound_projection_commitment_sha256,
                "audit reference projection digest",
            ),
        ] {
            validate_digest(digest, label)?;
        }
        if self.projections_equal
            != (self.broker_outbound_projection_commitment_sha256
                == self.reference_outbound_projection_commitment_sha256)
            || self.network_dispatch_count != 0
            || self.accounting_mutation_count != 0
            || self.raw_credential_returned
        {
            return Err(BrokerError::InvalidRequest(
                "broker audit comparison safety claims are inconsistent".to_string(),
            ));
        }
        Ok(())
    }
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct BrokerAuditGovernedIntent<'a> {
    schema: &'static str,
    audit_id: &'a str,
    runner_authorization_sha256: &'a str,
}

/// Compute the exact governed intent that operators approve for one audit
/// comparison. The digest binds the live request, the secret-bearing reference,
/// its provenance label, and the authority domain without exposing reference
/// bytes in the signed comparison artifact.
fn broker_audit_governed_intent_digest(
    runner: &BrokerAuditRunnerAuthorizationBody,
    runner_authorization_sha256: &str,
) -> Result<String> {
    runner.validate()?;
    validate_digest(
        runner_authorization_sha256,
        "broker audit runner authorization digest",
    )?;
    let canonical = canonical_json_bytes(&BrokerAuditGovernedIntent {
        schema: BROKER_AUDIT_GOVERNED_INTENT_SCHEMA,
        audit_id: &runner.audit_id,
        runner_authorization_sha256,
    })
    .map_err(|error| {
        BrokerError::Invariant(format!("broker audit intent encoding failed: {error}"))
    })?;
    let mut hasher = Sha256::new();
    hasher.update(BROKER_AUDIT_GOVERNED_INTENT_DOMAIN);
    hasher.update(canonical);
    Ok(hex::encode(hasher.finalize()))
}

fn runner_authorization_signing_bytes(
    body: &BrokerAuditRunnerAuthorizationBody,
) -> Result<Vec<u8>> {
    body.validate()?;
    let canonical = canonical_json_bytes(body).map_err(|error| {
        BrokerError::Invariant(format!(
            "broker audit runner authorization body encoding failed: {error}"
        ))
    })?;
    let mut signing = Vec::with_capacity(
        BROKER_AUDIT_RUNNER_AUTHORIZATION_SIGNATURE_DOMAIN.len() + canonical.len(),
    );
    signing.extend_from_slice(BROKER_AUDIT_RUNNER_AUTHORIZATION_SIGNATURE_DOMAIN);
    signing.extend_from_slice(&canonical);
    Ok(signing)
}

fn runner_authorization_digest(
    authorization: &SignedBrokerAuditRunnerAuthorization,
) -> Result<String> {
    authorization.verify_signature()?;
    let canonical = canonical_json_bytes(authorization).map_err(|error| {
        BrokerError::Invariant(format!(
            "broker audit runner authorization digest encoding failed: {error}"
        ))
    })?;
    let mut hasher = Sha256::new();
    hasher.update(BROKER_AUDIT_RUNNER_AUTHORIZATION_DIGEST_DOMAIN);
    hasher.update(canonical);
    Ok(hex::encode(hasher.finalize()))
}

/// Compute the exact governed intent that threshold operators must approve for
/// one self-signed runner authorization.
pub fn broker_audit_governed_intent_for_runner_authorization(
    authorization: &SignedBrokerAuditRunnerAuthorization,
) -> Result<String> {
    let runner_authorization_sha256 = runner_authorization_digest(authorization)?;
    broker_audit_governed_intent_digest(&authorization.body, &runner_authorization_sha256)
}

pub(crate) fn broker_audit_id_digest(audit_id: &str) -> Result<String> {
    validate_identifier(audit_id, "broker audit identifier", 512)?;
    let mut hasher = Sha256::new();
    hasher.update(BROKER_AUDIT_ID_DOMAIN);
    hasher.update(audit_id.as_bytes());
    Ok(hex::encode(hasher.finalize()))
}

pub(crate) fn broker_audit_reference_source_digest(reference_source: &str) -> Result<String> {
    validate_identifier(reference_source, "audit reference source", 512)?;
    let mut hasher = Sha256::new();
    hasher.update(BROKER_AUDIT_REFERENCE_SOURCE_DOMAIN);
    hasher.update(reference_source.as_bytes());
    Ok(hex::encode(hasher.finalize()))
}

fn validate_reference_request_parts(request_head: &[u8], request_body: &[u8]) -> Result<()> {
    if request_head.is_empty()
        || request_head.len() > MAX_WIRE_BYTES
        || !request_head.ends_with(b"\r\n\r\n")
        || request_body.len() > MAX_BODY_BYTES
    {
        return Err(BrokerError::InvalidRequest(
            "broker audit reference request is malformed or oversized".to_string(),
        ));
    }
    Ok(())
}

fn validate_reference_commitment_salt(commitment_salt: &str) -> Result<()> {
    validate_digest(
        commitment_salt,
        "broker audit runner reference commitment salt",
    )?;
    if commitment_salt.bytes().all(|byte| byte == b'0') {
        return Err(BrokerError::InvalidRequest(
            "broker audit runner reference commitment salt is all zero".to_string(),
        ));
    }
    Ok(())
}

/// Derive the blinded reference commitment from runner-owned inputs.
///
/// Audit runners call this before connecting to the broker and retain the
/// typed [`BrokerAuditReferencePrecommitment`] through evidence verification.
pub fn broker_audit_reference_commitment_sha256(
    commitment_salt: &str,
    request_head: &[u8],
    request_body: &[u8],
) -> Result<String> {
    validate_reference_request_parts(request_head, request_body)?;
    validate_reference_commitment_salt(commitment_salt)?;
    let salt = Zeroizing::new(hex::decode(commitment_salt).map_err(|_| {
        BrokerError::InvalidRequest(
            "broker audit runner reference commitment salt is invalid".to_string(),
        )
    })?);
    if salt.len() != BROKER_AUDIT_REFERENCE_COMMITMENT_SALT_BYTES {
        return Err(BrokerError::InvalidRequest(
            "broker audit runner reference commitment salt has the wrong length".to_string(),
        ));
    }
    let head_len = u64::try_from(request_head.len()).map_err(|_| {
        BrokerError::InvalidRequest("audit reference head length overflow".to_string())
    })?;
    let body_len = u64::try_from(request_body.len()).map_err(|_| {
        BrokerError::InvalidRequest("audit reference body length overflow".to_string())
    })?;
    let mut hasher = Sha256::new();
    hasher.update(BROKER_AUDIT_REFERENCE_DIGEST_DOMAIN);
    hasher.update(salt.as_slice());
    hasher.update(head_len.to_be_bytes());
    hasher.update(request_head);
    hasher.update(body_len.to_be_bytes());
    hasher.update(request_body);
    Ok(hex::encode(hasher.finalize()))
}

fn reference_request_digest(reference: &BrokerAuditReferenceRequest) -> Result<String> {
    broker_audit_reference_commitment_sha256(
        reference.commitment_salt.as_str(),
        reference.request_head.as_slice(),
        reference.request_body.as_slice(),
    )
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SignedBrokerAuditComparison {
    pub body: BrokerAuditComparisonBody,
    pub signer: PublicKey,
    pub algorithm: SigningAlgorithm,
    pub signature: Signature,
}

impl SignedBrokerAuditComparison {
    pub fn canonical_bytes(&self) -> Result<Vec<u8>> {
        self.verify_signature()?;
        let canonical = canonical_json_bytes(self).map_err(|error| {
            BrokerError::Invariant(format!(
                "broker audit comparison canonical encoding failed: {error}"
            ))
        })?;
        if canonical.len() > MAX_AUDIT_COMPARISON_BYTES {
            return Err(BrokerError::InvalidRequest(
                "broker audit comparison exceeds its canonical wire limit".to_string(),
            ));
        }
        Ok(canonical)
    }

    pub fn from_canonical_bytes(bytes: &[u8]) -> Result<Self> {
        if bytes.is_empty() || bytes.len() > MAX_AUDIT_COMPARISON_BYTES {
            return Err(BrokerError::InvalidRequest(
                "broker audit comparison is empty or oversized".to_string(),
            ));
        }
        let comparison: Self = serde_json::from_slice(bytes).map_err(|error| {
            BrokerError::InvalidRequest(format!("broker audit comparison decoding failed: {error}"))
        })?;
        comparison.verify_signature()?;
        if canonical_json_bytes(&comparison).map_err(|error| {
            BrokerError::InvalidRequest(format!(
                "broker audit comparison canonicalization failed: {error}"
            ))
        })? != bytes
        {
            return Err(BrokerError::InvalidRequest(
                "broker audit comparison is not canonical JSON".to_string(),
            ));
        }
        Ok(comparison)
    }

    fn verify_signature(&self) -> Result<()> {
        verify_broker_audit_comparison(self, &self.signer)
    }
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct BrokerAuditComparisonSigningInput<'a> {
    domain: &'static str,
    body: &'a BrokerAuditComparisonBody,
}

pub fn sign_broker_audit_comparison(
    body: BrokerAuditComparisonBody,
    signer: &dyn SigningBackend,
) -> Result<SignedBrokerAuditComparison> {
    body.validate()?;
    let signing = BrokerAuditComparisonSigningInput {
        domain: BROKER_AUDIT_COMPARISON_SIGNATURE_DOMAIN,
        body: &body,
    };
    let canonical = canonical_json_bytes(&signing).map_err(|error| {
        BrokerError::Invariant(format!(
            "broker audit comparison signing input encoding failed: {error}"
        ))
    })?;
    let signed = signer
        .sign_bytes_with_identity(&canonical)
        .map_err(|error| {
            BrokerError::Invariant(format!("broker audit comparison signing failed: {error}"))
        })?;
    if signed.public_key.algorithm() != signed.algorithm
        || signed.signature.algorithm() != signed.algorithm
        || !signed.public_key.verify(&canonical, &signed.signature)
    {
        return Err(BrokerError::Invariant(
            "broker audit comparison signer returned a mismatched identity or signature"
                .to_string(),
        ));
    }
    Ok(SignedBrokerAuditComparison {
        body,
        signer: signed.public_key,
        algorithm: signed.algorithm,
        signature: signed.signature,
    })
}

pub fn verify_broker_audit_comparison(
    comparison: &SignedBrokerAuditComparison,
    trusted_signer: &PublicKey,
) -> Result<()> {
    comparison.body.validate().map_err(|error| {
        BrokerError::AuthorizationDenied(format!(
            "broker audit comparison body is invalid: {error}"
        ))
    })?;
    if &comparison.signer != trusted_signer
        || comparison.signer.algorithm() != comparison.algorithm
        || comparison.signature.algorithm() != comparison.algorithm
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit comparison signer or algorithm is invalid".to_string(),
        ));
    }
    let signing = BrokerAuditComparisonSigningInput {
        domain: BROKER_AUDIT_COMPARISON_SIGNATURE_DOMAIN,
        body: &comparison.body,
    };
    if !comparison
        .signer
        .verify_canonical(&signing, &comparison.signature)
        .map_err(|error| {
            BrokerError::AuthorizationDenied(format!(
                "broker audit comparison verification failed: {error}"
            ))
        })?
    {
        return Err(BrokerError::AuthorizationDenied(
            "broker audit comparison signature is invalid".to_string(),
        ));
    }
    Ok(())
}

#[derive(Clone, Copy)]
pub struct BrokerAuditTrustConfiguration<'a> {
    pub trusted_capability_issuer: &'a PublicKey,
    pub broker_audience: &'a str,
    pub parent_audience: &'a str,
    pub provider_adapter_id: &'a str,
    pub provider_adapter_version: u32,
    pub receipt_signer: &'a PublicKey,
    pub maximum_clock_skew_seconds: u64,
    pub maximum_liveness_snapshot_age_seconds: u64,
    pub maximum_revocation_snapshot_age_seconds: u64,
    pub trusted_authority: &'a PublicKey,
    pub deployment_id: &'a str,
    pub broker_instance_id: &'a str,
    pub tenant_scope: &'a str,
    pub runner_id: &'a str,
    pub trusted_runner: &'a PublicKey,
    pub governed_admin_policy: &'a GovernedAdminPolicy,
}

impl BrokerAuditTrustConfiguration<'_> {
    fn validate(&self) -> Result<()> {
        for (value, label) in [
            (self.broker_audience, "audit broker audience"),
            (self.parent_audience, "audit parent audience"),
            (self.provider_adapter_id, "audit provider adapter"),
            (self.deployment_id, "audit deployment identifier"),
            (self.broker_instance_id, "audit broker instance"),
            (self.tenant_scope, "audit tenant scope"),
            (self.runner_id, "audit runner identifier"),
        ] {
            validate_identifier(value, label, 512)?;
        }
        if self.provider_adapter_version == 0
            || self.maximum_clock_skew_seconds > 60
            || self.maximum_liveness_snapshot_age_seconds == 0
            || self.maximum_liveness_snapshot_age_seconds > 60
            || self.maximum_revocation_snapshot_age_seconds == 0
            || self.maximum_revocation_snapshot_age_seconds > 60
        {
            return Err(BrokerError::InvalidRequest(
                "broker audit trust configuration bounds are invalid".to_string(),
            ));
        }
        self.governed_admin_policy.validate_for_runtime()
    }

    pub fn digest(&self) -> Result<String> {
        self.validate()?;
        let mut trusted_approvers = self.governed_admin_policy.trusted_approvers.clone();
        trusted_approvers.sort_unstable_by_key(PublicKey::to_hex);

        #[derive(Serialize)]
        #[serde(rename_all = "camelCase", deny_unknown_fields)]
        struct CanonicalAdminPolicy<'a> {
            trusted_approvers: &'a [PublicKey],
            subject: &'a PublicKey,
            threshold: usize,
            maximum_token_lifetime_seconds: u64,
        }

        #[derive(Serialize)]
        #[serde(rename_all = "camelCase", deny_unknown_fields)]
        struct CanonicalTrustConfiguration<'a> {
            trusted_capability_issuer: &'a PublicKey,
            broker_audience: &'a str,
            parent_audience: &'a str,
            provider_adapter_id: &'a str,
            provider_adapter_version: u32,
            receipt_signer: &'a PublicKey,
            maximum_clock_skew_seconds: u64,
            maximum_liveness_snapshot_age_seconds: u64,
            maximum_revocation_snapshot_age_seconds: u64,
            trusted_authority: &'a PublicKey,
            deployment_id: &'a str,
            broker_instance_id: &'a str,
            tenant_scope: &'a str,
            runner_id: &'a str,
            trusted_runner: &'a PublicKey,
            governed_admin_policy: CanonicalAdminPolicy<'a>,
        }

        let canonical = canonical_json_bytes(&CanonicalTrustConfiguration {
            trusted_capability_issuer: self.trusted_capability_issuer,
            broker_audience: self.broker_audience,
            parent_audience: self.parent_audience,
            provider_adapter_id: self.provider_adapter_id,
            provider_adapter_version: self.provider_adapter_version,
            receipt_signer: self.receipt_signer,
            maximum_clock_skew_seconds: self.maximum_clock_skew_seconds,
            maximum_liveness_snapshot_age_seconds: self.maximum_liveness_snapshot_age_seconds,
            maximum_revocation_snapshot_age_seconds: self.maximum_revocation_snapshot_age_seconds,
            trusted_authority: self.trusted_authority,
            deployment_id: self.deployment_id,
            broker_instance_id: self.broker_instance_id,
            tenant_scope: self.tenant_scope,
            runner_id: self.runner_id,
            trusted_runner: self.trusted_runner,
            governed_admin_policy: CanonicalAdminPolicy {
                trusted_approvers: &trusted_approvers,
                subject: &self.governed_admin_policy.subject,
                threshold: self.governed_admin_policy.threshold,
                maximum_token_lifetime_seconds: self
                    .governed_admin_policy
                    .maximum_token_lifetime_seconds,
            },
        })
        .map_err(|error| {
            BrokerError::Invariant(format!(
                "broker audit trust configuration encoding failed: {error}"
            ))
        })?;
        let mut hasher = Sha256::new();
        hasher.update(BROKER_AUDIT_TRUSTED_CONFIGURATION_DOMAIN);
        hasher.update(canonical);
        Ok(hex::encode(hasher.finalize()))
    }
}

