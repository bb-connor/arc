use std::fs;

use chio_core_types::KNOWN_SIGNED_ARTIFACT_SCHEMAS;

use crate::support::{display_path, workspace_root};
use crate::XtaskError;

const TS_OUT: &str = "sdks/typescript/chio-ts/src/invariants/_generated/signed_artifact_schemas.ts";
const PYTHON_OUT: &str =
    "sdks/python/chio-py/src/chio/invariants/_generated_signed_artifact_schemas.py";
const GO_OUT: &str = "sdks/go/chio-go/invariants/signed_artifact_schemas_gen.go";

const HEADER: &str = "Generated by `cargo xtask codegen` from chio_core_types::KNOWN_SIGNED_ARTIFACT_SCHEMAS. Do not edit.";

/// Sorted, deduplicated wrapper ids. Fails when the Rust list carries a
/// duplicate, since a duplicate means two artifact types share one id.
fn sorted_ids() -> Result<Vec<&'static str>, XtaskError> {
    let mut ids: Vec<&'static str> = KNOWN_SIGNED_ARTIFACT_SCHEMAS.to_vec();
    ids.sort_unstable();
    if let Some(pair) = ids.windows(2).find(|pair| pair.first() == pair.get(1)) {
        return Err(XtaskError::Usage(format!(
            "codegen: KNOWN_SIGNED_ARTIFACT_SCHEMAS lists {} twice",
            pair.first().copied().unwrap_or_default()
        )));
    }
    if let Some(id) = ids
        .iter()
        .find(|id| id.contains(['"', '\\', '\n']) || !id.is_ascii())
    {
        return Err(XtaskError::Usage(format!(
            "codegen: signed-artifact schema id {id:?} is not a plain ASCII literal"
        )));
    }
    Ok(ids)
}

pub(super) fn render_ts(ids: &[&str]) -> String {
    let mut out = format!("// {HEADER}\n\nexport const KNOWN_SIGNED_ARTIFACT_SCHEMAS: readonly string[] = Object.freeze([\n");
    for id in ids {
        out.push_str(&format!("  \"{id}\",\n"));
    }
    out.push_str("]);\n\nconst KNOWN = new Set<string>(KNOWN_SIGNED_ARTIFACT_SCHEMAS);\n\n");
    out.push_str("export function isRegisteredWrapperSchema(schemaId: string): boolean {\n  return KNOWN.has(schemaId);\n}\n");
    out
}

pub(super) fn render_python(ids: &[&str]) -> String {
    let mut out = format!("# {HEADER}\n\nfrom __future__ import annotations\n\nKNOWN_SIGNED_ARTIFACT_SCHEMAS: frozenset[str] = frozenset(\n    {{\n");
    for id in ids {
        out.push_str(&format!("        \"{id}\",\n"));
    }
    out.push_str("    }\n)\n\n\ndef is_registered_wrapper_schema(schema_id: str) -> bool:\n    return schema_id in KNOWN_SIGNED_ARTIFACT_SCHEMAS\n");
    out
}

pub(super) fn render_go(ids: &[&str]) -> String {
    let mut out = String::from("// Code generated by `cargo xtask codegen` from chio_core_types::KNOWN_SIGNED_ARTIFACT_SCHEMAS. DO NOT EDIT.\n\npackage invariants\n\n// KnownSignedArtifactSchemas holds every registered signing-wrapper schema id, sorted.\nvar KnownSignedArtifactSchemas = []string{\n");
    for id in ids {
        out.push_str(&format!("\t\"{id}\",\n"));
    }
    out.push_str("}\n\nvar knownSignedArtifactSchemas = func() map[string]struct{} {\n\tset := make(map[string]struct{}, len(KnownSignedArtifactSchemas))\n\tfor _, id := range KnownSignedArtifactSchemas {\n\t\tset[id] = struct{}{}\n\t}\n\treturn set\n}()\n\n// IsRegisteredWrapperSchema reports whether the signing wrapper may sign or verify under schemaID.\nfunc IsRegisteredWrapperSchema(schemaID string) bool {\n\t_, ok := knownSignedArtifactSchemas[schemaID]\n\treturn ok\n}\n");
    out
}

/// Write, or with `check_only` compare, the SDK copy of the wrapper id list
/// for `lang`. `rust` has no copy: the SDKs mirror the Rust constant.
pub(super) fn codegen_signed_ids(lang: &str, check_only: bool) -> Result<(), XtaskError> {
    let ids = sorted_ids()?;
    let (rel, body) = match lang {
        "ts" => (TS_OUT, render_ts(&ids)),
        "python" => (PYTHON_OUT, render_python(&ids)),
        "go" => (GO_OUT, render_go(&ids)),
        _ => return Ok(()),
    };
    let path = workspace_root()?.join(rel);
    if check_only {
        let on_disk = match fs::read_to_string(&path) {
            Ok(text) => text,
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                return Err(XtaskError::Drift(format!(
                    "{} is missing; rerun `cargo xtask codegen --lang {lang}`",
                    display_path(&path)
                )));
            }
            Err(err) => return Err(XtaskError::Io(display_path(&path), err)),
        };
        if on_disk != body {
            return Err(XtaskError::Drift(format!(
                "{} is stale; rerun `cargo xtask codegen --lang {lang}`",
                display_path(&path)
            )));
        }
        println!(
            "codegen {lang}: {} in sync ({} ids)",
            display_path(&path),
            ids.len()
        );
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|err| XtaskError::Io(display_path(parent), err))?;
    }
    fs::write(&path, body.as_bytes()).map_err(|err| XtaskError::Io(display_path(&path), err))?;
    println!(
        "codegen {lang}: wrote {} ({} ids)",
        display_path(&path),
        ids.len()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const IDS: &[&str] = &["chio.a.v1", "chio.b.v1"];

    #[test]
    fn renderers_list_every_id_once_in_order() {
        for rendered in [render_ts(IDS), render_python(IDS), render_go(IDS)] {
            let a = rendered.find("\"chio.a.v1\"");
            let b = rendered.find("\"chio.b.v1\"");
            assert!(matches!((a, b), (Some(a), Some(b)) if a < b), "{rendered}");
            assert_eq!(rendered.matches("\"chio.a.v1\"").count(), 1, "{rendered}");
            assert!(rendered.ends_with('\n') && !rendered.ends_with("\n\n"));
        }
    }

    #[test]
    fn live_ids_are_unique_plain_literals() {
        let ids = sorted_ids();
        assert!(ids.is_ok(), "{ids:?}");
        assert_eq!(
            ids.map(|ids| ids.len()).unwrap_or_default(),
            KNOWN_SIGNED_ARTIFACT_SCHEMAS.len()
        );
    }

    #[test]
    fn go_output_is_marked_generated() {
        assert!(render_go(IDS).starts_with("// Code generated by"));
    }
}
